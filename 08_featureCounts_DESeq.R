# Function that accepts a DESeq results dataframe with a given contrast (i.e. DESeq2::results(dds, contrast = c("drug_treatment","ANS","untreated")))
# Outputs a dataframe ready to be used for ggplot2.
generate_ggplot2_dataframe <- function(dds_results_dataframe) {
  
  # Transforms input dataframe, adding up + down columns to mark if a given gene (row) has a Log2FoldChange >/< 1. 
  dds_results_dataframe <- dds_results_dataframe %>% mutate(up = log2FoldChange > 1, down= log2FoldChange < -1)
  
  # Several genes have a p-value of zero, since they are NOT observed in the untreated condition. This leads to an infinite -log10(p-value), which breaks the ggplot2 labeling.
  # The below code adds the absolute minimum non-zero value allowable by R to the padj column and creates a new padj_padded column.
  dds_results_dataframe <- dplyr::mutate(dds_results_dataframe, padj_padded = padj + .Machine$double.xmin)
  
  # Changes genes names from ensembl_gene_id_versions to actual gene names as marked by the biomaRt database bm generated earlier.
  ensembl_gene_id_version <- rownames(dds_results_dataframe) 
  rownames(dds_results_dataframe) <- NULL
  dds_results_dataframe <- cbind(ensembl_gene_id_version,dds_results_dataframe)
  
  # Removes baseMeans that are 0.0000 (which I have no idea why they exist)
  dds_results_dataframe <- dplyr::filter(dds_results_dataframe, baseMean > 0)
  # Reformats dataframe to work well with downstream DESeq2 analyses and assigns gene names to correct rows
  dds_results_dataframe <- left_join(dds_results_dataframe, bm.complete, by="ensembl_gene_id_version")
  return(dds_results_dataframe)
}

# Function that accepts input dataframe generated by generate_ggplot2_dataframe and outputs a ggplot2 volcano plot.
plot_DESeq2_volcano <- function(cleaned_dataframe) {
  # Subsets "up" and "down" observations for plotting later.
  up_rows <- cleaned_dataframe[cleaned_dataframe$up == TRUE,]
  down_rows <- cleaned_dataframe[cleaned_dataframe$down == TRUE,]
  
  ggplot(cleaned_dataframe, aes(x=log2FoldChange,
                   y=-log10(padj_padded))) +
    geom_point(alpha=0.2, pch=16, color="grey50") +
    geom_point(data=up_rows, color="#377EB8", alpha=0.2) +
    geom_hline(yintercept=0, linetype="dashed", color = "black") +
    geom_vline(xintercept=0, linetype="dashed", color = "black") +
    geom_text_repel(data=up_rows, aes(label=external_gene_name), point.padding=0.25) +
    geom_text_repel(data=down_rows, aes(label=external_gene_name), point.padding=0.25) +
    theme_bw()
}

# Wrapper function that accepts a DESeq2 object (generated by DESeq()) as well as treatment conditions + control_conditions
# Outputs dataframe ready to be plotted by the plot_DESeq2_volcano() function or plot_crossCorrelation() function
wrapper_deseq2_results_to_ggplot2_dataframe <- function(deseq_object, treatment_condition, control_condition) {
  deseq_results <- DESeq2::results(deseq_object, contrast = c("drug_treatment", treatment_condition, control_condition))
  results_dataframe <- as.data.frame(deseq_results)
  results_dataframe <- generate_ggplot2_dataframe(results_dataframe)
}

# Wrapper function that accepts a DESeq2 object (generated by DESeq()) and a given ensembl_gene_id for a given gene (ex. "ENSG00000162772.18", which is ATF3)
# Outputs ggplot of those counts
wrapper_plotCounts <- function(deseq2_dataframe, ensembl_geneid) {
  # Example of usage (for JUN)
  # wrapper_plotCounts(dds, "ENSG00000120129.6")
  
  # Uses DESeq2's plotCounts() to return a dataframe of the normalized read counts for the given gene for each condition
  deseq2_plotCounts_dataframe <- plotCounts(dds, gene=ensembl_geneid, intgroup="drug_treatment", returnData=TRUE)
  
  # Uses the bm.complete data pulled earlier to find the external_gene_name that is human-readable, using the ensembl_gene_id_version
  gene_name <-unlist(dplyr::filter(bm.complete, ensembl_gene_id_version == ensembl_geneid)["external_gene_name"])
  names(gene_name) <- NULL
  gene_name <- paste(gene_name, ensembl_geneid,sep=" | ")
  
  # Plots the plotCounts data
  ggplot(deseq2_plotCounts_dataframe, aes(x=drug_treatment, y=count)) + 
    geom_point(position=position_jitter(w=0.1,h=0)) + 
    scale_y_log10(breaks=c(25,100,400)) + ggtitle(gene_name)
  
}

# Function that accepts two ggplot2_dataframes generated by wrapper_deseq2_results_to_ggplot2_dataframe and respective labels
# Outputs cross-correlation plot
plot_crossCorrelation <- function(treatmentA_df, treatmentB_df, labelA, labelB) {
  # Example of usage:
  # ANS_UT <- wrapper_deseq2_results_to_ggplot2_dataframe(dds,"ANS","untreated")
  # EME_UT <- wrapper_deseq2_results_to_ggplot2_dataframe(dds, "DDB","untreated")
  # plot_crossCorrelation(ANS_UT, EME_UT, ".ANS",".DDB")
  
  # Generates combined dataframe of the two specified dataframes
  combined_df <- inner_join(treatmentA_df, treatmentB_df, by="ensembl_gene_id_version", suffix=c(labelA, labelB))
  
  # Creates symbol of each dataframe's log2FoldChange label in the combined_df to pass into ggplot later
  xaxis <- paste("log2FoldChange",labelA, sep="")
  yaxis <- paste("log2FoldChange",labelB,sep="")
  xaxis <- sym(xaxis)
  yaxis <- sym(yaxis)
  
  # Plots correlation plot using log2FoldChange symbols generated earlier
  ggplot(combined_df, aes(x=!!xaxis,
                   y=!!yaxis)) +
    ylim(-5,5) +
    xlim(-5,5) +
    geom_point(alpha=0.2, pch=16, color="grey50") +
    geom_hline(yintercept=0, linetype="dashed", color = "black") +
    geom_vline(xintercept=0, linetype="dashed", color = "black") +
    theme_bw()
  

}

