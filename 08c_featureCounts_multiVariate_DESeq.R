# Get dataframe of human-readable gene names to relabel rows (which use the ensembl gene ids) later
get_ENS <- function(dset="hsapiens_gene_ensembl") {
  mart <- useMart("ENSEMBL_MART_ENSEMBL", dataset = dset)
  attributes <- c("ensembl_gene_id","ensembl_gene_id_version", "external_gene_name",
                  "chromosome_name", "start_position", "end_position")
  bm <- getBM(attributes, mart = mart)
  return(bm)
}

bm <- get_ENS()
bm

# Drop any rows in bm dataframe with no external_gene_names
bm.complete <-dplyr::filter(bm, ! external_gene_name == '')
bm.complete

# Read featureCounts.txt file generated by 06c_featureCounts_countMatrix.sh on the command line
featureCounts <- read.delim("../06c_featureCounts_countMatrix/JL318_featureCounts_countMatrix.txt", sep="\t",skip=1)

# Drop unimportant columns
featureCounts <- dplyr::select(featureCounts, -c("Chr","Start","Strand","End","Strand","Length"))

# Redefine rownames as Geneids for DESeq2
rownames(featureCounts) <- featureCounts[,"Geneid"]

# Drop Geneid column
featureCounts <- dplyr::select(featureCounts, -c("Geneid"))

# Trim column names to just the conditions (without the paths and extraneous suffices)
colnames(featureCounts) <- sub('\\b...05_STAR_alignments.JL318.','',colnames(featureCounts))
colnames(featureCounts) <- sub('_STARAligned.sortedByCoord.out.bam\\b','',colnames(featureCounts))

# Create new dataframe of the conditions based on the ones in the count Matrix
samples <- colnames(featureCounts)
samples <- as.data.frame(samples)
samples

# Add ZAKi column to samples dataframe based on if sample was +ZAKi or not.
samples$ZAKi <- NA
samples$ZAKi <- ifelse(endsWith(samples$samples,".A"), "noZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".B"), "noZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".C"), "noZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".D"), "noZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".E"), "ZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".F"), "ZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".G"), "ZAKi", no=samples$ZAKi)
samples$ZAKi <- ifelse(endsWith(samples$samples,".H"), "ZAKi", no=samples$ZAKi)

# Add Replicate column to samples dataframe
samples$Rep <- NA
samples$Rep <-ifelse(startsWith(samples$samples, "Rep1."), 1, no=samples$Rep)
samples$Rep <-ifelse(startsWith(samples$samples, "Rep2."), 2, no=samples$Rep)
samples$Rep <-ifelse(startsWith(samples$samples, "Rep3."), 3, no=samples$Rep)
samples

# Add drug column to samples dataframe based on what drug was applied to each sample
samples$drug <- NA
samples$drug <- ifelse(endsWith(samples$samples,".A"), "untreated", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".B"), "ANS", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".C"), "EME", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".D"), "DDB", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".E"), "untreated", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".F"), "ANS", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".G"), "EME", no=samples$drug)
samples$drug <- ifelse(endsWith(samples$samples,".H"), "DDB", no=samples$drug)

rownames(samples) <- samples$samples
samples

# Reassign samples$drug_treatment variable as factor type in specific order
samples$drug <- factor(samples$drug, levels = c("untreated","ANS","EME","DDB"))
samples$ZAKi <- factor(samples$ZAKi, levels = c("noZAKi","ZAKi"))

# Run DESeq2 using the featureCounts and samples dataframes we generated above, using the drug_treatment column listed in the samples dataframe
dds <- DESeqDataSetFromMatrix(countData = featureCounts, colData=samples,design=~drug + ZAKi + drug:ZAKi)
dds <- DESeq(dds)

# Removes rows with less than 100 reads, but only for 3 samples (the smallest group size - each condition has 3 replicates)
# I previously dropped rows with less than 100 reads in ALL 24 samples, which led to me losing major ZAK-responsive genes such as FOS and JUNB.
idx <- rowSums(counts(dds, normalized=TRUE) >= 100 ) >= 3
dds <- dds[idx,]

# Plots dispersion plot for diagnostics. Nicolle mentioned that the fit should be as flat as possible (it tends to tail up for <100 mean of normalized counts).
# Removing rows with less than 100 reads will help.
plotDispEsts(dds)

res <- results(dds)

# Generate PCA plot of the DESeq results
vsd <- vst(dds,blind=FALSE)

plotPCA(vsd,intgroup=c("drug", "ZAKi"))

# Return DESeq2 PCAplot data as a separate dataframe for custom ggplot
PCAplot_data <- plotPCA(vsd,intgroup=c("drug_treatment"), returnData=TRUE)

# Plot PCA DESeq2 data using ggplot2.
PCAplot <- ggplot(PCAplot_data, aes(x = PC1, y = PC2, color = group, shape = group)) +
  geom_point(size = 4, stroke = 2) +
  theme_bw(base_family = "Avenir") +
  theme(legend.title = element_text(size = 20, face="bold"),
        legend.text = element_text(size = 18),
        axis.text = element_text(size = 18),
        axis.title = element_text(size = 20, face="bold"),
        plot.title = element_text(size = 20, face = "bold"),
        panel.grid = element_line(color = "dark grey"),
        legend.key.spacing.y = unit(0.5, "lines")) + 
  coord_fixed() + 
  ggtitle("RNA-seq PCA") +
  scale_color_manual(name = "group", 
                     labels = c("Untreated","Untreated+ZAKi", "ANS","ANS+ZAKi", "EME","EME+ZAKi", "DDB", "DDB+ZAKi"),
                     values = c("#afafaf", "#afafaf", "#b100ff", "#b100ff", "#084152","#084152", "#62d5b4", "#62d5b4")) +
  scale_shape_manual(name = "group", 
                     labels = c("Untreated","Untreated+ZAKi", "ANS","ANS+ZAKi", "EME","EME+ZAKi", "DDB", "DDB+ZAKi"),
                     values = c(19,1,19,1,19,1,19,1)) +
  # Used % variances calculated by plotPCA(vsd, intgroup = c("drug_treatment"))
  labs(x = "PC1: 67% variance",
       y = "PC2: 17% variance")

# View PCA Plot
PCAplot

